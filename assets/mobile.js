/* ============================================================
   «САЙТ ДЛЯ АМДЦ» — ПОВЕДЕНИЕ ТЕЛЕФОННОЙ ВЕРСИИ.

   Ни библиотек, ни сборки — как и в основном скрипте.

   ── Что делает ───────────────────────────────────────────
   Из шестнадцати развёрнутых разворотов собирает двенадцать
   читаемых: длинные перечни прячет под спойлеры, а после
   ключевых блоков ставит полосу мессенджеров.

   ── Почему скриптом, а не в разметке ─────────────────────
   Десктопная версия утверждена и её трогать нельзя. Если
   писать спойлеры руками в index.html, придётся держать в
   разметке две структуры сразу — одну для широкого экрана,
   другую для узкого, — и любая правка текста делается
   дважды. Здесь разметка одна, а телефонная структура
   собирается из неё при загрузке.

   ── Что будет, если скрипт не выполнится ─────────────────
   Ничего не сломается: страница останется той же, что была
   до правки, просто длиннее. Ни один смысл не прячется в
   скрипт — он только перекладывает уже готовые узлы.
   ============================================================ */

(function(){
  'use strict';

  var MOB = '(max-width:860px)';
  if (!matchMedia(MOB).matches) return;

  var WA = '79111112122';
  var TG = 'https://t.me/+79111112122';

  /* ---- 1. Спойлер ---------------------------------------
     Собирает <details> вокруг списка узлов и ставит его туда,
     где стоял первый из них. Заголовок — не «подробнее», а
     сам тезис: человек должен знать, что откроет. */
  function spoiler(nodes, title, opts){
    nodes = [].slice.call(nodes).filter(Boolean);
    if (!nodes.length) return null;

    opts = opts || {};
    var d  = document.createElement('details');
    d.className = 'mob-sp' + (opts.wide ? ' wide' : '');

    var s  = document.createElement('summary');
    s.appendChild(document.createTextNode(title));
    if (opts.count !== false){
      var c = document.createElement('span');
      c.className = 'cnt';
      c.textContent = '+' + (opts.count || nodes.length);
      s.appendChild(c);
    }

    var box = document.createElement('div');
    box.className = 'in';

    nodes[0].parentNode.insertBefore(d, nodes[0]);
    nodes.forEach(function(n){ box.appendChild(n); });
    d.appendChild(s);
    d.appendChild(box);
    return d;
  }

  /* ---- 2. Полоса мессенджеров ---------------------------
     Правило методички: кнопки мессенджеров расставлены по
     всему листу, а не только в подвале. Ставится после
     блоков, где у читателя возникает вопрос. */
  function messengers(afterEl, question, waText){
    if (!afterEl) return;
    var box = document.createElement('div');
    box.className = 'mob-msg';
    box.innerHTML =
      '<div class="q">' + question + '</div>' +
      '<a class="wa" href="https://wa.me/' + WA + '?text=' +
        encodeURIComponent(waText) + '" target="_blank" rel="noopener">' +
        '<svg class="i"><use href="#i-wa"/></svg>WhatsApp</a>' +
      '<a class="tg" href="' + TG + '" target="_blank" rel="noopener">' +
        '<svg class="i"><use href="#i-tg"/></svg>Telegram</a>';
    afterEl.appendChild(box);
    return box;
  }

  function sec(n){ return document.querySelector('section[data-sec="' + n + '"]'); }
  function wrapOf(n){ var s = sec(n); return s && s.querySelector('.wrap'); }

  /* ========================================================
     03. АУДИТ САЙТА

     Семь находок и шестнадцать строк чужого кода. На виду
     остаются четыре находки — те, что понятны без пояснений;
     остальные три и сам код уходят под спойлеры.
     ======================================================== */
  (function(){
    var s = sec('s03'); if (!s) return;

    var found = s.querySelectorAll('.findings li');
    if (found.length > 4){
      spoiler([].slice.call(found).slice(4),
              'Ещё три находки на сайте');
    }

    var code = s.querySelector('.code');
    var note = s.querySelector('.aside');
    if (code){
      spoiler([code, note].filter(Boolean),
              'Показать исходный код am-dc.ru',
              {count:false, wide:true});
    }

    messengers(s.querySelector('.wrap'),
      'Хотите тот же разбор письмом — или спросить по любому пункту?',
      'Здравствуйте! Это АМДЦ. Вопрос по разбору сайта am-dc.ru.');
  })();

  /* ========================================================
     05. ФОРМА ПРОТОТИПА

     Правило: вся форма с призывом помещается в один экран.
     Обязательное — имя, номер, кнопка. «Когда написать» и
     «что важно учесть» прячутся: они помогают мне, а не
     ему, и не должны стоять между ним и кнопкой.
     ======================================================== */
  (function(){
    var f = document.querySelector('#start form'); if (!f) return;

    var fields = f.querySelectorAll('.field');
    if (fields.length >= 4){
      spoiler([fields[2], fields[3]],
              'Добавить пожелания',
              {count:false});
    }

    /* спойлер обязан стоять над кнопкой, а не под ней */
    var btn = f.querySelector('button[type=submit]');
    var sp  = f.querySelector('.mob-sp');
    if (btn && sp) btn.parentNode.insertBefore(sp, btn);
  })();

  /* ========================================================
     04. АРИФМЕТИКА

     Воронка и ведомость рассказывают одно и то же: 420 → 305
     → 18 → 13. На широком экране они стоят рядом и читаются
     как картинка и её расшифровка. На телефоне идут друг за
     другом — и это ровно та «перегрузка блока», которую
     методичка называет четвёртой по частоте ошибкой.

     На виду остаётся воронка: она короче и нагляднее.
     Ведомость с коэффициентами — под спойлером, для того,
     кто захочет проверить арифметику по шагам.
     ======================================================== */
  (function(){
    var t = document.querySelector('[data-sec="s04"] .ledger');
    if (t) spoiler([t], 'Показать расчёт по шагам', {count:false});
  })();

  /* ========================================================
     06. ШЕСТЬ ВЫГОД

     Самый длинный блок страницы: два с половиной экрана
     однообразных карточек. Две первые несут главный смысл
     (находят по услуге, видно цену) — остаются. Четыре
     остальные складываются в один спойлер.
     ======================================================== */
  (function(){
    var g = document.querySelectorAll('[data-sec="s06"] .gain');
    if (g.length > 2){
      spoiler([].slice.call(g).slice(2),
              'Ещё четыре вещи, которые начнут работать');
    }
  })();

  /* ========================================================
     07. НАПРАВЛЕНИЯ

     Кольцо и четырнадцать чипов — это и есть смысл блока:
     видно, что зачёркнуто одиннадцать позиций. Три цифры
     под ними (50+, 0, 11) доказывают то же самое ещё раз,
     только словами. Уходят под спойлер, чтобы блок остался
     в один смысл и один экран.
     ======================================================== */
  (function(){
    var f = document.querySelector('[data-sec="s07"] .facts');
    if (f) spoiler([f], 'Три цифры, которые это подтверждают', {count:false});
  })();

  messengers(wrapOf('s07'),
    'Хотите проверить, какие направления запускать первыми?',
    'Здравствуйте! Это АМДЦ. Хочу обсудить, с каких направлений начать.');

  /* ========================================================
     09. СОСЕДИ ПО КВАРТАЛУ

     Четыре карточки: три конкурента и вы. Сильнее всех бьёт
     первая — «Амрита», тот же дом, та же лестница. Её и
     оставляем на виду вместе с вашей строкой, а двух
     дальних соседей прячем: они подтверждают мысль, но не
     создают её.
     ======================================================== */
  (function(){
    var rows = document.querySelectorAll('[data-sec="s09"] .vs .row');
    if (rows.length < 4) return;
    spoiler([rows[1], rows[2]], 'Ещё двое в пяти минутах ходьбы');
    /* карточка АМДЦ обязана остаться последней: на ней
       строится вывод блока */
    var me = rows[3];
    me.parentNode.appendChild(me);
  })();

  /* 09. Сразу после сравнения с соседями — самый горячий
     момент на всей странице: только что стало видно, чем
     они берут. */
  messengers(wrapOf('s09'),
    'Хотите такую же страницу, как у соседей, — только свою?',
    'Здравствуйте! Это АМДЦ. Посмотрел сравнение с соседями, хочу обсудить сайт.');

  /* ========================================================
     11. ПРИМЕР РАБОТЫ — полоса мессенджеров
     ======================================================== */
  messengers(wrapOf('s11'),
    'Показать ещё работы или ответить на вопрос по этой?',
    'Здравствуйте! Это АМДЦ. Видел сайт «Дофамин», есть вопрос.');

  /* 13. Под списком вопросов — единственное место, где
     предложение написать выглядит не продажей, а ответом
     на то, чего в списке не нашлось. */
  messengers(wrapOf('s13'),
    'Остался вопрос, которого тут нет? Спросите — отвечу сам.',
    'Здравствуйте! Это АМДЦ. У меня вопрос по предложению.');

  /* ========================================================
     14. СОСТАВ РАБОТЫ

     Семнадцать пунктов в трёх колонках. Каждая колонка
     становится спойлером, а её заголовок — надписью на нём:
     «Смыслы и структура», «Сайт», «Запуск». Тезис на месте,
     полотна нет.
     ======================================================== */
  (function(){
    var cols = document.querySelectorAll('[data-sec="s14"] .incl .col');
    [].slice.call(cols).forEach(function(col){
      var h  = col.querySelector('h3');
      var ul = col.querySelector('ul');
      if (!h || !ul) return;
      var d = spoiler([ul], h.textContent.trim(),
                      {count: ul.children.length});
      if (d) { col.appendChild(d); h.remove(); }
    });
  })();

  /* ========================================================
     15. ЧЕРЕЗ ГОД

     Блок повторяет приём второго раздела — два исхода в две
     колонки — и на телефоне читается как уже прочитанное.
     Методичка требует оставить 10–12 блоков из шестнадцати;
     этот сворачивается целиком, но не выбрасывается: кто
     дочитал до конца, тот его откроет.
     ======================================================== */
  (function(){
    var s = sec('s15'); if (!s) return;
    var t = s.querySelector('.tickets'); if (!t) return;
    spoiler([t], 'Посмотреть, что будет через год', {count:false});
  })();

  /* ---- 3. Спойлеры в полосе прокрутки -------------------
     details раскрывается мгновенно, и содержимое выталкивает
     страницу вниз рывком. Подводим заголовок спойлера к
     верхнему краю, чтобы раскрытое оказалось перед глазами,
     а не уехало под сгиб. */
  document.addEventListener('toggle', function(e){
    var d = e.target;
    if (!d.classList || !d.classList.contains('mob-sp') || !d.open) return;
    var top = d.getBoundingClientRect().top;
    var hdr = parseInt(getComputedStyle(document.documentElement)
                .getPropertyValue('--hdr'), 10) || 56;
    if (top < hdr + 8 || top > innerHeight * 0.55){
      scrollBy({top: top - hdr - 12, behavior: 'smooth'});
    }
  }, true);

  /* ---- 4. Блоки внутри спойлера показываются сразу -------
     Основной скрипт прячет блоки до попадания в экран через
     IntersectionObserver. Содержимое закрытого спойлера в
     экран не попадает никогда, поэтому при первом раскрытии
     оно осталось бы невидимым. */
  document.addEventListener('toggle', function(e){
    var d = e.target;
    if (!d.classList || !d.classList.contains('mob-sp') || !d.open) return;
    d.querySelectorAll('[data-rise]').forEach(function(el){
      el.classList.add('seen');
    });
  }, true);

  /* ---- 5. Когда выпускать липкую полосу -----------------
     Основной скрипт считает порогом три четверти первого
     экрана. На телефоне hero занимает два с лишним экрана,
     и по этому правилу кнопка внизу появлялась только на
     третьем — полтора экрана человек листал без неё.

     Здесь порог другой и честный: полоса выезжает ровно
     тогда, когда кнопка первого экрана ушла из виду. Пока
     она на месте, дублировать её внизу незачем — методичка
     на этот счёт однозначна. */
  (function(){
    var cta = document.querySelector('.hero .ctarow');
    var root = document.documentElement;
    if (!cta) { root.classList.add('sticky-ready'); return; }

    if (!('IntersectionObserver' in window)){
      root.classList.add('sticky-ready');
      return;
    }
    new IntersectionObserver(function(e){
      root.classList.toggle('sticky-ready', !e[0].isIntersecting);
    }, {threshold:0}).observe(cta);
  })();

  document.documentElement.classList.add('mob');
})();
